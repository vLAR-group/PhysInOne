"""Generate train/infer/novel/resimulate Bash batches from a generated config manifest."""
import argparse
import json
import os
from pathlib import Path
import re
import shlex

from generate_configs import MATERIALS, write_plan

ROOT = Path(__file__).resolve().parent
MODES = ('train', 'infer', 'novel', 'resimulate')


def project_relative(path):
    try:
        return Path(os.path.relpath(path, ROOT)).as_posix()
    except ValueError:
        raise ValueError('Keep generated configs/scripts on the project drive for portable Bash paths') from None


def selected_records(manifest, materials=None, gaps=None):
    records, seen = [], set()
    for record in manifest['records']:
        case, gap, material = record['case_name'], record['gap'], record['material']
        if not isinstance(case, str) or not re.fullmatch(r'[A-Za-z0-9_]+', case):
            raise ValueError(f'Invalid case name: {case!r}')
        if isinstance(gap, bool) or not isinstance(gap, int) or gap < 1:
            raise ValueError(f'{case}: gap must be a positive integer')
        if material not in MATERIALS.values():
            raise ValueError(f'Unsupported material: {material}')
        key = (case, gap)
        if key in seen:
            raise ValueError(f'Duplicate case/gap in manifest: {key}')
        seen.add(key)
        if (materials and material not in materials) or (gaps and gap not in gaps):
            continue
        frames = record['render_frames']
        if isinstance(frames, bool) or not isinstance(frames, int) or frames < 1:
            raise ValueError(f'{case}: render_frames must be a positive integer')
        records.append(record)
    if not records:
        raise ValueError('No cases match the selected materials/gaps')
    return sorted(records, key=lambda r: (r['material'], r['case_name'], r['gap']))


def config_paths(record, manifest_dir):
    result = {}
    for mode in MODES:
        path = (manifest_dir / record['configs'][mode]).resolve()
        if not path.is_relative_to(manifest_dir.resolve()) or path.suffix != '.json':
            raise ValueError(f'Config must be a JSON file inside the manifest directory: {path}')
        if not path.is_file():
            raise FileNotFoundError(path)
        result[mode] = project_relative(path)
    return result


def script_header(output_dir, python, gpu):
    try:
        relative = Path(os.path.relpath(ROOT, output_dir)).as_posix()
    except ValueError:
        raise ValueError('Keep generated scripts on the same drive as the project') from None
    lines = [
        '#!/usr/bin/env bash',
        '# Generated by generate_scripts.py; do not edit individual case commands.',
        'set -euo pipefail',
        'SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"',
        'cd -- "$SCRIPT_DIR"/' + shlex.quote(relative),
        'if [[ -z "${PYTHON:-}" ]]; then',
        '  export PYTHON=' + shlex.quote(python),
        'else',
        '  export PYTHON',
        'fi',
    ]
    if gpu is not None:
        lines.append('export CUDA_VISIBLE_DEVICES=' + shlex.quote(gpu))
    return '\n'.join(lines) + '\n\n'


def build_plan(args, manifest):
    manifest_dir = Path(args.manifest).resolve().parent
    output_dir = Path(args.output_dir).resolve()
    records = selected_records(manifest, args.material, args.gap)
    paths = [config_paths(record, manifest_dir) for record in records]
    header = script_header(output_dir, args.python, args.gpu)
    files = {}
    for mode in MODES:
        lines = []
        for index, (record, configs) in enumerate(zip(records, paths), 1):
            label = f'[{index}/{len(records)}] {mode}: {record["case_name"]} gap{record["gap"]}'
            lines.append('printf \'%s\\n\' ' + shlex.quote(label))
            command = ['train_dynamic.py' if mode == 'train' else 'test.py',
                       '--config_path' if mode == 'train' else '--config', configs[mode]]
            if mode != 'train':
                command += ['--mode', mode]
                if mode != 'infer':
                    command += ['--cam-id', 'all']
            lines.append('"$PYTHON" ' + shlex.join(command))
            lines.append('')
        files[output_dir / (mode + '.sh')] = header + '\n'.join(lines) + '\n'
    files[output_dir / 'all.sh'] = header + '\n'.join(
        '"$BASH" "$SCRIPT_DIR/' + mode + '.sh"' for mode in MODES) + '\n'
    return files, records


def config_parser():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', default=str(ROOT / 'config/generated/manifest.json'))
    parser.add_argument('--output-dir', default=str(ROOT / 'scripts/generated'))
    parser.add_argument('--material', nargs='+', choices=sorted(MATERIALS.values()), default=None)
    parser.add_argument('--gap', nargs='+', type=int, default=None)
    parser.add_argument('--python', default='python', help='Python executable; PYTHON environment variable takes priority')
    parser.add_argument('--gpu', default=None, help='Set CUDA_VISIBLE_DEVICES, e.g. 0 or 0,1; default preserves environment')
    parser.add_argument('--overwrite', action='store_true')
    return parser


def main(argv=None):
    parser = config_parser()
    args = parser.parse_args(argv)
    if args.gap and any(gap < 1 for gap in args.gap):
        parser.error('--gap must be positive')
    if args.gpu is not None and not re.fullmatch(r'\d+(?:,\d+)*', args.gpu):
        parser.error('--gpu expects nonnegative indices such as 0 or 0,1')
    if not args.python.strip() or '\n' in args.python or '\r' in args.python:
        parser.error('--python must name one executable')
    with Path(args.manifest).open(encoding='utf-8-sig') as stream:
        manifest = json.load(stream)
    files, records = build_plan(args, manifest)
    written = write_plan(files, args.overwrite)
    for path in files:
        path.chmod(path.stat().st_mode | 0o111)
    print(f'Generated 5 Bash scripts for {len(records)} case/gap pairs ({written} files written)')
    print(f'Output: {Path(args.output_dir).resolve()}')
    print('Infer fits once per case; render commands reuse it for all cameras; scripts stop on failure.')
    return files


if __name__ == '__main__':
    main()
